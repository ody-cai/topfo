# ---- 日期常量 ----
DATE_PATCHES = [
    ("const DATA_REV_DATE = '2026-10-11';", "const DATA_REV_DATE = '2026-10-12';"),
    ("const DATA_UPDATED = '2026-10-11';", "const DATA_UPDATED = '2026-10-12';"),
]


def append_to_deadline(src, school, addition):
    key = "{name:'%s'" % school
    i = src.find(key)
    if i < 0:
        return src, 'NONAME'
    j = src.find(",tuition:'", i)
    if j < 0:
        return src, 'NOTUITION'
    if src[j - 1] != "'":
        return src, 'QUOTE'
    return src[:j - 1] + addition + src[j - 1:], 'OK'


def run(paths):
    for path in paths:
        if not os.path.exists(path):
            print('FILE MISSING', path); continue
        src = io.open(path, encoding='utf-8').read()
        miss = []
        for school, addition in ADD:
            src2, status = append_to_deadline(src, school, addition)
            if status == 'OK':
                src = src2
            else:
                miss.append((school, status))
        hits = 0
        for old, new in DATE_PATCHES:
            c = src.count(old)
            if c >= 1:
                src = src.replace(old, new); hits += c
            else:
                miss.append((old[:40], 'DATE0'))
        io.open(path, 'w', encoding='utf-8').write(src)
        print('%-46s schools=%d/%d dates=%d %s' % (
            os.path.relpath(path, ROOT), len(ADD) - len(miss), len(ADD), hits,
            ('MISS %s' % miss) if miss else 'ALL HIT'))


if __name__ == '__main__':
    run(FILES)
