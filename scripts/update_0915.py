report = []

def patch(path, pairs, must_all=True):
    with io.open(path, encoding="utf-8") as f:
        s = f.read()
    orig = s
    for old, new in pairs:
        n = s.count(old)
        if n == 0:
            report.append("  [MISS] %s :: %s" % (os.path.basename(path), old[:70]))
            if must_all:
                continue
            continue
        s = s.replace(old, new)
        report.append("  [OK x%d] %s :: %s" % (n, os.path.basename(path), old[:60]))
    if s != orig:
        with io.open(path, "w", encoding="utf-8") as f:
            f.write(s)
        report.append("  [WROTE] %s" % path)
    else:
        report.append("  [NOCHANGE] %s" % path)
    return s

