    anchor = "\n---\n\n> **本轮数据来源**"
    if s.count(anchor) == 1:
        s = s.replace(anchor, "\n" + NEW_SECTION + "\n> **上一轮数据来源（2026-10-06）**")
        print("   HIT  M5 新增「三·补九」整节")
    else:
        print("   MISS(%d) M5 新章节锚点" % s.count(anchor)); miss += 1
    open(MD, 'w', encoding='utf-8').write(s)
    print("\nMD MISS = %d" % miss)
    return miss

